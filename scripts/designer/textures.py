#!/usr/bin/env python3
"""
Build the décor patterns the home designer draws wood, stone and wall panels with.

    python3 scripts/designer/textures.py

A flat colour is fine for paint and vinyl siding, but Grizzly Oak, the wood-look
floors, the marble and pine countertops and the Waycross wall panels are a
pattern, and one median colour of them reads as a different product (Grizzly Oak
became orange paint). So for the finishes listed in `scripts/designer/patterns/patterns.json` (kept out of
scripts/designer/ itself, where build.py reads every .json as a home)
this crops the board's own swatch (`public/designer/swatches/<id>.webp`), scales it
to photo size and mirrors it into a seamless tile at
`public/designer/textures/<id>.webp`, and writes what the browser needs to
`app/lib/designer/textures.generated.ts`.
"""
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent.parent
SPEC = ROOT / "scripts" / "designer" / "patterns" / "patterns.json"
SWATCHES = ROOT / "public" / "designer" / "swatches"
OUT = ROOT / "public" / "designer" / "textures"
OUT_TS = ROOT / "app" / "lib" / "designer" / "textures.generated.ts"


def tile(id_, s):
    im = Image.open(SWATCHES / f"{id_}.webp").convert("RGB")
    w, h = im.size
    x0, y0, x1, y1 = s["crop"]
    c = im.crop((round(x0 * w), round(y0 * h), round(x1 * w), round(y1 * h)))
    c = c.resize((max(1, round(c.width * s["scale"])), max(1, round(c.height * s["scale"]))), Image.LANCZOS)
    t = Image.new("RGB", (c.width * 2, c.height * 2))
    t.paste(c, (0, 0))
    t.paste(ImageOps.mirror(c), (c.width, 0))
    t.paste(ImageOps.flip(c), (0, c.height))
    t.paste(ImageOps.flip(ImageOps.mirror(c)), (c.width, c.height))
    return t


def main():
    spec = json.loads(SPEC.read_text())["finishes"]
    OUT.mkdir(parents=True, exist_ok=True)
    gen = {}
    for id_, s in spec.items():
        t = tile(id_, s)
        t.save(OUT / f"{id_}.webp", quality=88, method=6)
        gen[id_] = {"src": f"/designer/textures/{id_}.webp", "on": s["on"], "amp": s["amp"], "detail": s["detail"]}
        print(f"{id_}: {t.width}x{t.height}")
    OUT_TS.write_text(
        "/* GENERATED by scripts/designer/textures.py from scripts/designer/patterns/patterns.json — do not edit. */\n"
        'import type { Material } from "./types";\n\n'
        "/** Finishes drawn as the board's own pattern, on the surfaces listed. */\n"
        "export const decorTextures: Record<string, { src: string; on: Material[]; amp: number; detail: number }> = "
        + json.dumps(gen, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    main()
